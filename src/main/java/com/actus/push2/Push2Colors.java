    /** Nearest palette index (Euclidean RGB distance) to the given 0-1 float color. */
    static int nearest(final float red, final float green, final float blue)
    {
        final int r = Math.round(red * 255f);
        final int g = Math.round(green * 255f);
        final int b = Math.round(blue * 255f);

        int bestIndex = 0;
        int bestDistance = Integer.MAX_VALUE;
        for (int i = 0; i < PALETTE.length; i++)
        {
            final int dr = PALETTE[i][0] - r;
            final int dg = PALETTE[i][1] - g;
            final int db = PALETTE[i][2] - b;
            final int distance = dr * dr + dg * dg + db * db;
            if (distance < bestDistance)
            {
                bestDistance = distance;
                bestIndex = i;
            }
        }
        return bestIndex;
    }
